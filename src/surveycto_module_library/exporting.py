from __future__ import annotations

import io
import json

import pandas as pd
from openpyxl.styles import Alignment, Font, PatternFill

MAX_EXCEL_CELL_CHARS = 32_760


def export_workbook(frame: pd.DataFrame) -> bytes:
    choice_rows = []
    for row in frame.itertuples():
        for choice in row.choices:
            choice_rows.append(
                {
                    "form_id": row.form_id,
                    "survey": row.survey,
                    "module": row.module,
                    "field_name": row.field_name,
                    "choice_value": choice.get("value"),
                    "choice_labels": json.dumps(choice.get("labels", {}), ensure_ascii=False),
                }
            )
    results = frame.copy()
    for column in ("labels", "hints", "choices", "dependencies", "group_path"):
        if column in results:
            results[column] = results[column].map(
                lambda value: (
                    json.dumps(value, ensure_ascii=False)
                    if isinstance(value, (dict, list))
                    else value
                )
            )
    results = results.map(_excel_safe)
    private_columns = ["labels_json", "hints_json", "group_path_json", "stable_id", "module_id"]
    results = results.drop(
        columns=[column for column in private_columns if column in results], errors="ignore"
    )
    modules = results[["topic", "subtopic", "form_id", "survey", "module"]].drop_duplicates()
    questions = results[
        [
            "form_id",
            "survey",
            "module",
            "row_order",
            "field_name",
            "field_type",
            "question_text",
            "language",
            "choices",
            "relevance",
            "constraint_text",
            "calculation",
            "appearance",
            "dependencies",
        ]
    ]
    choices = pd.DataFrame(
        choice_rows,
        columns=[
            "form_id",
            "survey",
            "module",
            "field_name",
            "choice_value",
            "choice_labels",
        ],
    ).map(_excel_safe)
    metadata = pd.DataFrame(
        [
            {"Item": "Generated by", "Value": "J-PAL MENA SurveyCTO Module Library"},
            {"Item": "Rows exported", "Value": len(results)},
            {"Item": "Surveys", "Value": results["form_id"].nunique()},
            {"Item": "Note", "Value": "Contains survey definitions only; no respondent data."},
        ]
    )
    output = io.BytesIO()
    with pd.ExcelWriter(output, engine="openpyxl") as writer:
        results.to_excel(writer, sheet_name="Results", index=False)
        modules.to_excel(writer, sheet_name="Modules", index=False)
        questions.to_excel(writer, sheet_name="Questions", index=False)
        choices.to_excel(writer, sheet_name="Choices", index=False)
        metadata.to_excel(writer, sheet_name="Metadata", index=False)
        for sheet in writer.book.worksheets:
            sheet.freeze_panes = "A2"
            sheet.auto_filter.ref = sheet.dimensions
            for cell in sheet[1]:
                cell.font = Font(bold=True, color="FFFFFF")
                cell.fill = PatternFill("solid", fgColor="2E5D4B")
                cell.alignment = Alignment(wrap_text=True)
            for column_cells in sheet.columns:
                max_length = max(len(str(cell.value or "")) for cell in list(column_cells)[:200])
                sheet.column_dimensions[column_cells[0].column_letter].width = min(
                    max(max_length + 2, 10), 48
                )
            for row in sheet.iter_rows(min_row=2):
                for cell in row:
                    cell.alignment = Alignment(vertical="top", wrap_text=True)
    return output.getvalue()


def _excel_safe(value):
    if isinstance(value, str) and len(value) > MAX_EXCEL_CELL_CHARS:
        return value[: MAX_EXCEL_CELL_CHARS - 22] + " ... [truncated in Excel]"
    return value
